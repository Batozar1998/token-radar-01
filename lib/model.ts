// Token Radar, model radar-2: the sealed snapshot in, a ranked board out.
//
// The board ranks every rankable pre-token protocol in the snapshot: the
// whole watchlist plus every rankable protocol below the watchlist floor.
// A protocol is pre-token when its DefiLlama record carries no token at
// all (no market cap, no CoinGecko id, no symbol). It is rankable when it
// is pre-token, not a CEX, not a versioned pool, and not a wrapped,
// staked or bridged product of a token that already trades — the
// watchlist's own exclusion, extended to the rows below the floor, so a
// staked-ETH product with a $7B TVL never ranks as a launch that has not
// happened yet.
//
// Implied value is calibrated from the snapshot's own live-token
// protocols, never from a hardcoded list of names:
//
//   implied = round( tvl_usd x category_multiple x growth_mult x maturity_mult )
//
//   category_multiple: the median mcap/TVL of the live-token protocols
//     in the row's category, shrunk toward the global median with a
//     prior weight of 3 and clamped to [0.05, 0.50]; a category with no
//     live comparables takes the global median. Medians, not means: one
//     outlier must not price a whole category.
//   growth_mult: 1 + clamp(change_7d, -60, 120) / 100 x 0.5.
//   maturity_mult: 0.6 + min(age_days, 1095) / 1095 x 0.4; age is the
//     days from listed_at to the snapshot date, 365 when unlisted.
//
// The same function scores every row. The dashboard recomputes each row
// from these inputs and says whether it matches board.json.

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  shrink_prior: number;
  multiple_floor: number;
  multiple_cap: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  shrink_prior: 3,
  multiple_floor: 0.05,
  multiple_cap: 0.5,
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
};

